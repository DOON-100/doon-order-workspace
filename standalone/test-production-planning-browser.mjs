async function assertInFirstScreen(current,id){
 const button=current.locator(`[data-nav-id="${id}"]`);await button.waitFor();
 const geometry=await button.evaluate(element=>{
  const r=element.getBoundingClientRect(),n=element.closest('nav').getBoundingClientRect();
  return {top:r.top,bottom:r.bottom,left:r.left,right:r.right,navTop:n.top,navBottom:n.bottom,width:innerWidth,height:innerHeight};
 });
 assert(geometry.top>=Math.max(0,geometry.navTop)&&geometry.bottom<=Math.min(geometry.height,geometry.navBottom)+1&&geometry.left>=0&&geometry.right<=geometry.width,`${id} must be visible before menu scrolling: ${JSON.stringify(geometry)}`);
}
async function assertNoHorizontalOverflow(current){
 const geometry=await current.evaluate(()=>{
  const selectors=['nav[aria-label="中台主导航"]','[data-nav-id]','.production-planning-nav-toggle','[data-production-planning]','[data-space-id]'];
  const rectangles=[...document.querySelectorAll(selectors.join(','))].filter(element=>element.getClientRects().length).map(element=>{
   const rect=element.getBoundingClientRect();
   return {id:element.getAttribute('data-nav-id')||element.getAttribute('data-space-id')||element.className,left:rect.left,right:rect.right,width:rect.width,scrollWidth:element.scrollWidth,clientWidth:element.clientWidth};
  });
  return {viewport:innerWidth,documentWidth:document.documentElement.scrollWidth,bodyWidth:document.body.scrollWidth,rectangles};
 });
 assert(geometry.documentWidth<=geometry.viewport+1&&geometry.bodyWidth<=geometry.viewport+1,'The page must not overflow horizontally: '+JSON.stringify(geometry));
 for(const rect of geometry.rectangles){
  assert(rect.left>=-1&&rect.right<=geometry.viewport+1,'Navigation/card stays within the viewport: '+JSON.stringify(rect));
  assert(rect.scrollWidth<=rect.clientWidth+1,'Navigation/card content fits its width: '+JSON.stringify(rect));
 }
}

