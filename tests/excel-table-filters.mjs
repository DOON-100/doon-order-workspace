import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {build} from 'esbuild';

const output=path.resolve('test-output','excel-table-filters-'+process.pid);
await fs.mkdir(output,{recursive:true});
const outfile=path.join(output,'filters.mjs');
await build({entryPoints:['app/excel-table.tsx'],outfile,bundle:true,platform:'node',format:'esm',packages:'external',alias:{'@':process.cwd()},loader:{'.css':'empty'}});
const {normalizeExcelValue,matchesExcelFilters}=await import(pathToFileURL(outfile).href);

assert.equal(normalizeExcelValue(null),'');
assert.equal(normalizeExcelValue(undefined),'');
assert.equal(normalizeExcelValue('  合成甲\n  第一组  '),'合成甲 第一组');
assert.equal(normalizeExcelValue(0),'0','Numeric zero is a filterable value, not blank.');
assert.equal(normalizeExcelValue(-12.5),'-12.5');
assert.equal(matchesExcelFilters(['甲','进行中',0],{}),true);
assert.equal(matchesExcelFilters(['甲','进行中',0],{2:['0']}),true);
assert.equal(matchesExcelFilters(['甲','进行中',0],{2:['']}),false);
assert.equal(matchesExcelFilters(['甲',null,0],{1:['']}),true);
assert.equal(matchesExcelFilters(['甲','进行中',0],{0:['甲','乙'],1:['进行中']}),true);
assert.equal(matchesExcelFilters(['甲','进行中',0],{0:['甲'],1:['已完成']}),false,'Columns combine with AND.');
assert.equal(matchesExcelFilters(['甲','进行中',0],{0:[]}),false,'Selecting no values must show no rows.');
assert.equal(matchesExcelFilters(['甲','进行中',0],{0:['甲'],4:['']}),true,'An absent optional field is blank.');

const records=Array.from({length:65},(_,index)=>({id:index+1,values:[index===64?'末页客户':'普通客户',index%2?'进行中':'已完成',index]}));
const original=JSON.stringify(records);
const filtered=records.filter(row=>matchesExcelFilters(row.values,{0:['末页客户']}));
assert.deepEqual(filtered.slice(0,10).map(row=>row.id),[65],'Filtering the complete dataset finds a record beyond the initial page.');
assert.deepEqual(records.filter(row=>matchesExcelFilters(row.values,{2:['0']})).map(row=>row.id),[1]);
assert.equal(JSON.stringify(records),original,'Filtering does not mutate original records.');
const refreshed=[...records,{id:66,values:['刷新客户','进行中',99]}];
assert.deepEqual(refreshed.filter(row=>matchesExcelFilters(row.values,{0:['刷新客户']})).map(row=>row.id),[66]);
assert.equal(records.filter(row=>matchesExcelFilters(row.values,{0:[]})).length,0);
assert.equal(records.filter(row=>matchesExcelFilters(row.values,{})).length,65,'Clearing filters restores every record.');
console.log('PASS Excel filters: blank and zero values, multi-selection, column intersection, full-data pagination, refresh, source immutability.');

const rulesFile=path.join(output,'rules.mjs');
await build({entryPoints:['lib/excel-filters.ts'],outfile:rulesFile,bundle:true,platform:'node',format:'esm'});
const {excelConditionError,excelNumber,excelDate,describeExcelFilter}=await import(pathToFileURL(rulesFile).href);
const match=(value,filter)=>matchesExcelFilters([value],{0:filter});
assert.equal(match('  PO-001 黑色 ',{kind:'text',operator:'contains',value:'po-001'}),true);
assert.equal(match('PO-001 黑色',{kind:'text',operator:'notContains',value:'黑色'}),false);
assert.equal(match('PO-001 黑色',{kind:'text',operator:'startsWith',value:'PO-'}),true);
assert.equal(match('PO-001 黑色',{kind:'text',operator:'endsWith',value:'黑色'}),true);
assert.equal(match('001',{kind:'text',operator:'equals',value:'1'}),false,'Text identifiers keep leading zeros.');
assert.equal(match('001',{kind:'text',operator:'notEquals',value:'1'}),true);
assert.equal(match('1,250.50',{kind:'number',operator:'between',value:'1,000',to:'1250.5'}),true);
assert.equal(match('1,25',{kind:'number',operator:'gte',value:'0'}),false,'Invalid grouping cannot silently change magnitude.');
assert.equal(match('12支',{kind:'number',operator:'equals',value:'12'}),false,'Composite displays are not parsed as arbitrary numeric prefixes.');
assert.equal(match('',{kind:'number',operator:'equals',value:'0'}),false);
assert.equal(match(null,{kind:'number',operator:'notEquals',value:'0'}),false);
assert.equal(match(0,{kind:'number',operator:'lte',value:'0'}),true);
assert.equal(match(-2.5,{kind:'number',operator:'gt',value:'-3'}),true);
assert.equal(match('13%',{kind:'number',operator:'equals',value:'0.13'}),true);
assert.equal(excelNumber(false),null);
assert.equal(excelNumber(1e21),1e21,'Typed numbers retain their value without converting through a display string.');
assert.equal(excelNumber(Infinity),null);
assert.equal(match(false,{kind:'blank',operator:'empty'}),false);
assert.equal(match(0,{kind:'blank',operator:'notEmpty'}),true);
assert.equal(match(undefined,{kind:'blank',operator:'empty'}),true);
assert.equal(match('#REF!',{kind:'blank',operator:'empty'}),false);
assert.equal(match('2026-10-30T23:30:00-08:00',{kind:'date',operator:'equals',value:'2026-10-30'}),true,'Date uses displayed date, never the browser timezone.');
assert.equal(match('2026/10/30',{kind:'date',operator:'between',value:'2026-10-01',to:'2026-10-30'}),true);
assert.equal(match('2026-11-01',{kind:'date',operator:'before',value:'2026-11-01'}),false);
assert.equal(match('2026-11-02',{kind:'date',operator:'after',value:'2026-11-01'}),true);
assert.equal(excelDate('2026-02-29'),null);
assert.notEqual(excelDate('2024-02-29'),null);
assert.equal(excelDate('2026-10-30 到 2026-11-01'),null);
assert.ok(excelConditionError({kind:'number',operator:'between',value:'10',to:'2'}));
assert.ok(excelConditionError({kind:'date',operator:'between',value:'2026-10-30',to:''}));
assert.ok(excelConditionError({kind:'text',operator:'contains',value:' '}));
assert.deepEqual(records.filter(row=>matchesExcelFilters(row.values,{0:{kind:'text',operator:'contains',value:'客户'},2:{kind:'number',operator:'between',value:'60',to:'64'},1:['已完成']})).map(row=>row.id),[61,63,65],'Typed conditions intersect across full data before paging.');
assert.equal(describeExcelFilter({kind:'number',operator:'between',value:'1',to:'3'}),'区间 1 至 3');
assert.equal(JSON.stringify(records),original,'Condition matching never rewrites records.');
console.log('PASS Excel typed filters: text matching, numeric and date ranges, invalid values, percent, blank/zero, combined full-data conditions, descriptions.');

const workbookRules=path.join(output,'workbook-values.mjs');
await build({entryPoints:['lib/excel-workbook-filter-value.ts'],outfile:workbookRules,bundle:true,platform:'node',format:'esm',packages:'external'});
const {workbookFilterValue}=await import(pathToFileURL(workbookRules).href);
const cell=(raw,display,numberFormat=null,extra={})=>({type:typeof raw==='number'?'n':'s',value:raw,cachedValue:null,cacheStatus:'not-formula',unknownReason:null,display,numberFormat,...extra});
const rounded=workbookFilterValue(cell(0.004,'0.00','0.00'));
assert.equal(normalizeExcelValue(rounded),'0.00');
assert.equal(match(rounded,['0.00']),true,'Value selection uses the visible label.');
assert.equal(match(rounded,{kind:'number',operator:'equals',value:'0'}),false,'Rounded display must not replace the raw number.');
assert.equal(match(rounded,{kind:'number',operator:'equals',value:'0.004'}),true);
assert.equal(match(workbookFilterValue(cell(1234.5,'￥1,234.50','"￥"#,##0.00')),{kind:'number',operator:'between',value:'1234',to:'1235'}),true);
assert.equal(match(workbookFilterValue(cell(0.125,'12.5%','0.0%')),{kind:'number',operator:'equals',value:'12.5%'}),true);
assert.equal(match(workbookFilterValue(cell(null,'0.00','0.00',{cachedValue:0.004,cacheStatus:'present',type:'n'})),{kind:'number',operator:'equals',value:'0'}),false,'Formula filtering uses its stored unrounded cache.');
const missing=workbookFilterValue(cell(null,'〔公式缓存缺失〕',null,{cacheStatus:'missing'}));
assert.equal(match(missing,{kind:'number',operator:'equals',value:'0'}),false);
assert.equal(match(missing,{kind:'blank',operator:'empty'}),false);
assert.equal(match(workbookFilterValue(cell(null,'',null,{unknownReason:'blank'})),{kind:'blank',operator:'empty'}),true);
assert.equal(match(workbookFilterValue(cell(null,'',null,{cacheStatus:'present',cachedValue:''})),{kind:'blank',operator:'empty'}),false,'Formula empty string is not an absent cell.');
assert.equal(match(workbookFilterValue(cell(7,'#DIV/0!',null,{type:'e',unknownReason:'error'})),{kind:'number',operator:'equals',value:'7'}),false);
assert.equal(match(workbookFilterValue(cell('001','001')),{kind:'number',operator:'equals',value:'1'}),false,'Typed text identifiers are never coerced to numeric quantities.');
const date1900=workbookFilterValue(cell(46325,'2026年10月30日','yyyy"年"m"月"d"日"'));
assert.equal(date1900.type,'date');
assert.equal(match(date1900,{kind:'date',operator:'equals',value:'2026-10-30'}),true);
const date1904=workbookFilterValue(cell(44863,'30/10/2026','dd/mm/yyyy'),true);
assert.equal(match(date1904,{kind:'date',operator:'equals',value:'2026-10-30'}),true,'1904 date system changes the serial conversion.');
assert.equal(match(date1900,{kind:'number',operator:'equals',value:'46325'}),false,'Dates are not offered as numerical quantities.');
console.log('PASS workbook filter values: unrounded numbers, currency/percent, formula caches, absent vs empty strings, typed identifiers and both Excel date systems.');
