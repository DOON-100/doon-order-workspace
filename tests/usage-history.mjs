import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {mkdtempSync, readFileSync, rmSync, existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {readUsageHistory} from '../scripts/view-usage-history.mjs';

const dir = mkdtempSync(join(tmpdir(), 'doon-usage-history-'));
const file = join(dir, 'synthetic.sqlite');
const now = Date.parse('2026-10-21T12:00:00Z');
let writer;
try {
  writer = new DatabaseSync(file);
  writer.exec(`PRAGMA journal_mode=WAL;
    CREATE TABLE records(id TEXT PRIMARY KEY, kind TEXT NOT NULL, data TEXT NOT NULL);
    CREATE TABLE local_accounts(username TEXT, member_id TEXT, password_hash TEXT);
    INSERT INTO local_accounts VALUES ('alice', 'member_a', 'SYNTHETIC_SECRET');`);
  const insert = writer.prepare('INSERT INTO records VALUES(?,?,?)');
  const put = (id, kind, extra = {}) => insert.run(id, kind, JSON.stringify({id, kind, createdAt:'2026-10-21T10:00:00Z', ...extra}));
  put('login', 'auth_event', {username:'alice', actorId:'member_a', action:'登录成功'});
  put('failed', 'auth_event', {username:'alice', actor:'未认证访问者', targetId:'member_a', action:'登录失败'});
  put('edit', 'audit', {actorId:'member_a', actor:'合成员工', action:'修改采购', before:{secret:'SYNTHETIC_SECRET'}, after:{secret:'SYNTHETIC_SECRET'}});
  put('other', 'audit', {actorId:'member_b'});
  put('old', 'audit', {actorId:'member_a', createdAt:'2026-09-01T00:00:00Z'});
  put('future', 'audit', {actorId:'member_a', createdAt:'2026-10-22T00:00:00Z'});
  put('boundary', 'audit', {actorId:'member_a', createdAt:'2026-10-14T20:00:00+08:00'});
  put('invalid-date', 'audit', {createdAt:'bad'});
  put('foreign', 'order', {secret:'SYNTHETIC_SECRET'});
  insert.run('malformed', 'audit', '{broken');
  const hash = name => createHash('sha256').update(readFileSync(name)).digest('hex');
  const before = [hash(file), hash(file + '-wal')];
  const report = readUsageHistory({db:file, username:'ALICE'}, now);
  assert.deepEqual(new Set(report.events.map(r => r.id)), new Set(['login','failed','edit','boundary']));
  assert(!JSON.stringify(report).includes('SYNTHETIC_SECRET'));
  assert.equal(readUsageHistory({db:file, kind:'login'}, now).returned, 2);
  assert.equal(readUsageHistory({db:file, 'member-id':'member_a'}, now).returned, 4);
  assert.equal(readUsageHistory({db:file, username:'alice', 'member-id':'member_b'}, now).returned, 0);
  assert.equal(readUsageHistory({db:file, limit:'1'}, now).truncated, true);
  assert.equal(readUsageHistory({db:file, username:'absent'}, now).returned, 0);
  assert.throws(() => readUsageHistory({db:file, days:'1 OR 1=1'}, now));
  assert.throws(() => readUsageHistory({db:file, kind:'unknown'}, now));
  assert.throws(() => readUsageHistory({db:file, limit:'0'}, now));
  assert.throws(() => readUsageHistory({}, now));
  const missing = join(dir, 'does-not-exist.sqlite');
  assert.throws(() => readUsageHistory({db:missing}, now));
  assert.equal(existsSync(missing), false);
  assert.deepEqual([hash(file), hash(file + '-wal')], before, 'reader must preserve database and WAL bytes');
  writer.exec('BEGIN;');
  put('uncommitted', 'audit');
  assert(!readUsageHistory({db:file}, now).events.some(row => row.id === 'uncommitted'));
  writer.exec('ROLLBACK;');
  writer.exec("DELETE FROM records WHERE kind='auth_event'; DROP TABLE local_accounts;");
  assert(readUsageHistory({db:file}, now).warnings.some(message => message.includes('没有登录事件')));
  assert(readUsageHistory({db:file, username:'alice'}, now).warnings.some(message => message.includes('无本地账号表')));
  const cli = spawnSync(process.execPath, ['scripts/view-usage-history.mjs', '--help'], {encoding:'utf8'});
  assert.equal(cli.status, 0); assert(cli.stdout.includes('--db'));
  const json = spawnSync(process.execPath, ['scripts/view-usage-history.mjs', '--db', file, '--days', '36500', '--json'], {encoding:'utf8'});
  assert.equal(json.status, 0); assert(Array.isArray(JSON.parse(json.stdout).events));
  console.log('PASS usage history: identity/time filters, WAL reads, no secret snapshots, unchanged DB/WAL, missing paths, legacy DB and CLI');
} finally {
  writer?.close();
  rmSync(dir, {recursive:true, force:true});
}
